-- ---------------------------------------------------------------------
-- 4. ACTUALIZACIÓN DEL PAQUETE PKG_TURISMOUQ (CUERPO)
-- ---------------------------------------------------------------------
CREATE OR REPLACE PACKAGE BODY pkg_turismouq IS

    -- =================================================================
    -- 1. fn_valor_estadia: cálculo por tramos de temporada sin bucles
    -- =================================================================
    FUNCTION fn_valor_estadia (
        p_id_habitacion IN NUMBER,
        p_fecha_in      IN DATE,
        p_fecha_out     IN DATE
    ) RETURN NUMBER IS
        v_total NUMBER := 0;
    BEGIN
        IF p_fecha_out <= p_fecha_in THEN
            RETURN 0;
        END IF;

        -- Intersección de intervalos [p_fecha_in, p_fecha_out] y [t.fecha_inicio, t.fecha_fin + 1]
        SELECT NVL(SUM(
                   (LEAST(p_fecha_out, t.fecha_fin + 1) - GREATEST(p_fecha_in, t.fecha_inicio)) * tf.valor_noche
               ), 0)
          INTO v_total
          FROM temporada t
          JOIN tarifa tf ON tf.id_temporada = t.id_temporada
         WHERE tf.id_habitacion = p_id_habitacion
           AND t.fecha_inicio < p_fecha_out
           AND t.fecha_fin >= p_fecha_in;

        RETURN v_total;
    END fn_valor_estadia;

    -- =================================================================
    -- 2. sp_crear_reserva: validaciones controladas y commit parametrizado
    -- =================================================================
    PROCEDURE sp_crear_reserva (
        p_id_cliente      IN  NUMBER,
        p_id_habitacion   IN  NUMBER,
        p_fecha_checkin   IN  DATE,
        p_fecha_checkout  IN  DATE,
        p_num_huespedes   IN  NUMBER,
        p_id_reserva      OUT NUMBER,
        p_commit          IN  BOOLEAN DEFAULT TRUE
    ) IS
        v_id_alojamiento  habitacion.id_alojamiento%TYPE;
        v_capacidad_max   habitacion.capacidad_max%TYPE;
        v_solapamientos   NUMBER := 0;
    BEGIN
        -- Validación 1: Fechas invertidas o iguales
        IF p_fecha_checkout <= p_fecha_checkin THEN
            RAISE_APPLICATION_ERROR(-20001, 'Error: La fecha de check-out (' || 
                TO_CHAR(p_fecha_checkout, 'YYYY-MM-DD') || 
                ') debe ser estrictamente posterior al check-in (' || 
                TO_CHAR(p_fecha_checkin, 'YYYY-MM-DD') || ').');
        END IF;

        -- Validación 2: Habitación y capacidad
        BEGIN
            SELECT id_alojamiento, capacidad_max
              INTO v_id_alojamiento, v_capacidad_max
              FROM habitacion
             WHERE id_habitacion = p_id_habitacion;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20004, 'Error: La habitacion con ID ' || p_id_habitacion || ' no existe.');
        END;

        IF p_num_huespedes > v_capacidad_max THEN
            RAISE_APPLICATION_ERROR(-20002, 'Error: Capacidad excedida. La habitacion soporta maximo ' || 
                v_capacidad_max || ' huespedes y se solicitaron ' || p_num_huespedes || '.');
        END IF;

        -- Validación 3: Solapamiento con reservas activas
        SELECT COUNT(*)
          INTO v_solapamientos
          FROM reserva_habitacion rh
          JOIN reserva r ON r.id_reserva = rh.id_reserva
         WHERE rh.id_habitacion = p_id_habitacion
           AND r.estado IN ('CONFIRMADA', 'PENDIENTE', 'COMPLETADA')
           AND rh.fecha_checkin  < p_fecha_checkout
           AND rh.fecha_checkout > p_fecha_checkin;

        IF v_solapamientos > 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Error: Habitacion no disponible. Ya existe una reserva activa en ese rango de fechas.');
        END IF;

        -- Inserción en cabecera RESERVA
        INSERT INTO reserva (
            id_cliente,
            id_alojamiento,
            fecha_creacion,
            fecha_checkin,
            fecha_checkout,
            estado,
            fecha_cancelacion
        ) VALUES (
            p_id_cliente,
            v_id_alojamiento,
            SYSDATE,
            p_fecha_checkin,
            p_fecha_checkout,
            'PENDIENTE',
            NULL
        ) RETURNING id_reserva INTO p_id_reserva;

        -- Inserción en detalle RESERVA_HABITACION
        INSERT INTO reserva_habitacion (
            id_reserva,
            id_habitacion,
            fecha_checkin,
            fecha_checkout,
            num_huespedes
        ) VALUES (
            p_id_reserva,
            p_id_habitacion,
            p_fecha_checkin,
            p_fecha_checkout,
            p_num_huespedes
        );

        -- Control transaccional según parámetro
        IF p_commit THEN
            COMMIT;
        END IF;
    END sp_crear_reserva;

    -- =================================================================
    -- 3. sp_reserva_con_pago_atomico: Transacción compuesta + SAVEPOINT
    -- =================================================================
    PROCEDURE sp_reserva_con_pago_atomico (
        p_id_cliente      IN  NUMBER,
        p_id_habitacion   IN  NUMBER,
        p_fecha_checkin   IN  DATE,
        p_fecha_checkout  IN  DATE,
        p_num_huespedes   IN  NUMBER,
        p_monto_pago      IN  NUMBER,
        p_metodo_pago     IN  VARCHAR2,
        p_id_reserva      OUT NUMBER,
        p_id_pago         OUT NUMBER,
        p_estado_final    OUT VARCHAR2
    ) IS
        v_costo_total NUMBER;
        v_mensaje     VARCHAR2(400);
    BEGIN
        p_id_pago := NULL;

        -- Paso 1: Crear la reserva SIN commit para mantener la sesión transaccional abierta
        sp_crear_reserva (
            p_id_cliente     => p_id_cliente,
            p_id_habitacion  => p_id_habitacion,
            p_fecha_checkin  => p_fecha_checkin,
            p_fecha_checkout => p_fecha_checkout,
            p_num_huespedes  => p_num_huespedes,
            p_id_reserva     => p_id_reserva,
            p_commit         => FALSE
        );

        -- Paso 2: Fijar punto de restauración parcial
        SAVEPOINT sp_post_reserva;

        -- Paso 3: Validar e intentar el registro del pago
        BEGIN
            -- Validar monto positivo
            IF p_monto_pago IS NULL OR p_monto_pago <= 0 THEN
                RAISE_APPLICATION_ERROR(-20020, 'El monto del pago debe ser estrictamente mayor a 0.');
            END IF;

            -- Validar suficiencia de cobertura contra la tarifa real
            v_costo_total := fn_valor_estadia(p_id_habitacion, p_fecha_checkin, p_fecha_checkout);
            IF p_monto_pago < v_costo_total THEN
                RAISE_APPLICATION_ERROR(-20021, 'Monto insuficiente (' || p_monto_pago || 
                                        '). El valor total de la estadia es ' || v_costo_total || '.');
            END IF;

            -- Insertar el pago (sometido a los CHECK de PAGO.metodo y PAGO.monto)
            INSERT INTO pago (
                id_reserva,
                fecha_pago,
                monto,
                metodo,
                estado
            ) VALUES (
                p_id_reserva,
                SYSDATE,
                p_monto_pago,
                UPPER(p_metodo_pago),
                'EXITOSO'
            ) RETURNING id_pago INTO p_id_pago;

            -- Si el pago tuvo éxito, actualizar estado de la reserva
            UPDATE reserva
               SET estado = 'CONFIRMADA'
             WHERE id_reserva = p_id_reserva;

            p_estado_final := 'CONFIRMADA';

            -- Confirmación de toda la transacción atómica
            COMMIT;

            INSERT INTO log_transaccion_reserva (id_reserva, resultado, mensaje_error)
            VALUES (p_id_reserva, 'TRANSACCION_EXITOSA', 'Reserva confirmada y pago exitoso');
            COMMIT;

        EXCEPTION
            WHEN OTHERS THEN
                -- ROLLBACK PARCIAL: Revierte el pago o intentos fallidos, pero mantiene la reserva
                ROLLBACK TO SAVEPOINT sp_post_reserva;

                p_id_pago      := NULL;
                p_estado_final := 'PENDIENTE';

                -- Consolidar la reserva en estado PENDIENTE de forma definitiva
                COMMIT;

                -- Capturar el mensaje de error en variable PL/SQL
                v_mensaje := SUBSTR(SQLERRM, 1, 400);

                -- Registrar en tabla de log transaccional autónomo
                INSERT INTO log_transaccion_reserva (id_reserva, resultado, mensaje_error)
                VALUES (p_id_reserva, 'PAGO_FALLIDO_REVERSADO', v_mensaje);
                COMMIT;
        END;

    END sp_reserva_con_pago_atomico;

    -- =================================================================
    -- 4. sp_liquidar_mensual
    -- =================================================================
    PROCEDURE sp_liquidar_mensual (
        p_anio           IN NUMBER,
        p_mes            IN NUMBER,
        p_id_alojamiento IN NUMBER DEFAULT NULL
    ) IS
        v_comision NUMBER := c_pct_comision;

        CURSOR c_liquidaciones IS
            WITH hospedaje_res AS (
                SELECT r.id_reserva,
                       r.id_alojamiento,
                       SUM(pkg_turismouq.fn_valor_estadia(rh.id_habitacion, rh.fecha_checkin, rh.fecha_checkout)) AS total_hospedaje
                  FROM reserva r
                  JOIN reserva_habitacion rh ON rh.id_reserva = r.id_reserva
                 WHERE r.estado = 'COMPLETADA'
                   AND EXTRACT(YEAR  FROM r.fecha_checkout) = p_anio
                   AND EXTRACT(MONTH FROM r.fecha_checkout) = p_mes
                 GROUP BY r.id_reserva, r.id_alojamiento
            ),
            servicios_res AS (
                SELECT r.id_reserva,
                       NVL(SUM(rs.cantidad * rs.precio_unitario), 0) AS total_servicios
                  FROM reserva r
                  JOIN reserva_servicio rs ON rs.id_reserva = r.id_reserva
                 WHERE r.estado = 'COMPLETADA'
                   AND EXTRACT(YEAR  FROM r.fecha_checkout) = p_anio
                   AND EXTRACT(MONTH FROM r.fecha_checkout) = p_mes
                 GROUP BY r.id_reserva
            ),
            consolidado_res AS (
                SELECT h.id_alojamiento,
                       h.id_reserva,
                       h.total_hospedaje + NVL(s.total_servicios, 0) AS ingreso_bruto
                  FROM hospedaje_res h
                  LEFT JOIN servicios_res s ON s.id_reserva = h.id_reserva
            )
            SELECT a.id_alojamiento,
                   a.nombre_comercial,
                   COUNT(c.id_reserva)          AS total_reservas,
                   NVL(SUM(c.ingreso_bruto), 0) AS total_bruto
              FROM alojamiento a
              LEFT JOIN consolidado_res c ON c.id_alojamiento = a.id_alojamiento
             WHERE (p_id_alojamiento IS NULL OR a.id_alojamiento = p_id_alojamiento)
             GROUP BY a.id_alojamiento, a.nombre_comercial
             ORDER BY total_bruto DESC;

        r_liq                  c_liquidaciones%ROWTYPE;
        v_comision_plataforma  NUMBER;
        v_neto_alojamiento     NUMBER;
    BEGIN
        OPEN c_liquidaciones;
        LOOP
            FETCH c_liquidaciones INTO r_liq;
            EXIT WHEN c_liquidaciones%NOTFOUND;

            v_comision_plataforma := NVL(r_liq.total_bruto, 0) * v_comision;
            v_neto_alojamiento    := NVL(r_liq.total_bruto, 0) * (1 - v_comision);

            DBMS_OUTPUT.PUT_LINE(
                'Alojamiento [' || RPAD(r_liq.id_alojamiento, 3) || '] ' ||
                RPAD(SUBSTR(r_liq.nombre_comercial, 1, 25), 25) || ' | ' ||
                'Reservas: ' || LPAD(r_liq.total_reservas, 4) || ' | ' ||
                'Bruto: $' || LPAD(TO_CHAR(r_liq.total_bruto, '999,999,999'), 12) || ' | ' ||
                'Neto: $'  || LPAD(TO_CHAR(v_neto_alojamiento, '999,999,999'), 12)
            );
        END LOOP;
        CLOSE c_liquidaciones;
    END sp_liquidar_mensual;

END pkg_turismouq;
