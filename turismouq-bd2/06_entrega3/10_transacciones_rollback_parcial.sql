-- DECISIÓN ARQUITECTURAL:
-- 1. Se modifica PKG_TURISMOUQ.SP_CREAR_RESERVA agregando p_commit BOOLEAN DEFAULT TRUE.
--    Esto preserva total retrocompatibilidad con las pruebas de Entrega 2.
-- 2. Se implementa SP_RESERVA_CON_PAGO_ATOMICO con SAVEPOINT 'sp_post_reserva'.
--    Si el registro del pago falla (por validación, CHECK constraint o error DML),
--    se realiza ROLLBACK TO sp_post_reserva: la reserva se conserva en 'PENDIENTE'
--    y no queda huella huérfana en la tabla PAGO. Si todo es exitoso, pasa a 'CONFIRMADA'.
-- 3. Se añade tabla LOG_TRANSACCION_RESERVA para registrar fallos sin perder trazabilidad.
-- 4. Se incorpora validación cruzada entre RESERVA.id_alojamiento y HABITACION.id_alojamiento.
-- =====================================================================

SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF

-- ---------------------------------------------------------------------
-- 1. TABLA DE AUDITORÍA Y TRAZABILIDAD DE LOG TRANSACCIONAL
-- ---------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE log_transaccion_reserva (
      id_log          NUMBER GENERATED BY DEFAULT AS IDENTITY,
      id_reserva      NUMBER,
      fecha_evento    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      resultado       VARCHAR2(20) NOT NULL,
      mensaje_error   VARCHAR2(400),
      CONSTRAINT pk_log_transaccion PRIMARY KEY (id_log)
    )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF; -- Ignora si ya existe ORA-00955
END;
/

-- ---------------------------------------------------------------------
-- 2. TRIGGER DEFENSIVO DE INTEGRIDAD CRUZADA
-- Valida que RESERVA_HABITACION no asocie habitaciones de otro alojamiento
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_valida_alojamiento_cruzado
BEFORE INSERT OR UPDATE ON reserva_habitacion
FOR EACH ROW
DECLARE
  v_alojamiento_reserva    reserva.id_alojamiento%TYPE;
  v_alojamiento_habitacion habitacion.id_alojamiento%TYPE;
BEGIN
  -- DECISIÓN: consultar alojamiento de la cabecera reserva y compararlo con el cuarto
  SELECT id_alojamiento INTO v_alojamiento_reserva
    FROM reserva
   WHERE id_reserva = :NEW.id_reserva;

  SELECT id_alojamiento INTO v_alojamiento_habitacion
    FROM habitacion
   WHERE id_habitacion = :NEW.id_habitacion;

  IF v_alojamiento_reserva <> v_alojamiento_habitacion THEN
    RAISE_APPLICATION_ERROR(-20010, 
      'Error de integridad: La habitacion ' || :NEW.id_habitacion || 
      ' pertenece al alojamiento ' || v_alojamiento_habitacion || 
      ' pero la reserva pertenece al alojamiento ' || v_alojamiento_reserva || '.');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    NULL; -- Si aún no se consolida en base, sp_crear_reserva garantiza consistencia
END;
/

