UPDATE tarifa 
   SET valor_noche = valor_noche + 15000 
 WHERE id_tarifa = 1;

COMMIT;

-- 3. Visualizar la evidencia de auditoría registrada por el disparador
SELECT id_auditoria,
       id_tarifa,
       usuario,
       TO_CHAR(fecha_cambio, 'YYYY-MM-DD HH24:MI:SS') AS fecha,
       operacion,
       valor_anterior,
       valor_nuevo,
       (valor_nuevo - valor_anterior) AS diferencia
  FROM auditoria_tarifa
 ORDER BY id_auditoria DESC;