CREATE TABLE auditoria_tarifa (
    id_auditoria    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_tarifa       NUMBER        NOT NULL,
    usuario         VARCHAR2(60)  NOT NULL,
    fecha_cambio    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    operacion       VARCHAR2(10)  NOT NULL,
    valor_anterior  NUMBER(12,2)  NOT NULL,
    valor_nuevo     NUMBER(12,2)  NOT NULL,
    CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria)
);

COMMENT ON TABLE auditoria_tarifa IS 'Registro historico de cambios de precios en las tarifas de habitaciones.';



CREATE OR REPLACE TRIGGER trg_auditoria_tarifa
FOR UPDATE OF valor_noche ON tarifa
COMPOUND TRIGGER

    -- Estructura en memoria para consolidar los cambios de la sentencia
    TYPE r_auditoria IS RECORD (
        id_tarifa      tarifa.id_tarifa%TYPE,
        valor_anterior tarifa.valor_noche%TYPE,
        valor_nuevo    tarifa.valor_noche%TYPE
    );
    TYPE t_auditoria IS TABLE OF r_auditoria INDEX BY PLS_INTEGER;
    v_cambios t_auditoria;

    -- Sección que captura los valores por cada fila modificada
    AFTER EACH ROW IS
    BEGIN
        -- Se audita únicamente si el valor efectivamente cambió
        IF :OLD.valor_noche <> :NEW.valor_noche THEN
            v_cambios(v_cambios.COUNT + 1).id_tarifa      := :OLD.id_tarifa;
            v_cambios(v_cambios.COUNT).valor_anterior    := :OLD.valor_noche;
            v_cambios(v_cambios.COUNT).valor_nuevo       := :NEW.valor_noche;
        END IF;
    END AFTER EACH ROW;

    -- Sección a nivel de sentencia: persiste todo el lote en una sola operación
    AFTER STATEMENT IS
    BEGIN
        FOR i IN 1 .. v_cambios.COUNT LOOP
            INSERT INTO auditoria_tarifa (
                id_tarifa,
                usuario,
                fecha_cambio,
                operacion,
                valor_anterior,
                valor_nuevo
            ) VALUES (
                v_cambios(i).id_tarifa,
                SYS_CONTEXT('USERENV', 'SESSION_USER'),
                SYSTIMESTAMP,
                'UPDATE',
                v_cambios(i).valor_anterior,
                v_cambios(i).valor_nuevo
            );
        END LOOP;
    END AFTER STATEMENT;

END trg_auditoria_tarifa;
/


