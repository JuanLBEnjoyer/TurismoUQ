

-- =====================================================================
-- 1. CREACIÓN DEL TABLESPACE PARA HISTÓRICO DE RESERVAS
-- =====================================================================
CREATE TABLESPACE ts_historico_reservas
    DATAFILE 'ts_historico_reservas.dbf' 
    SIZE 100M 
    AUTOEXTEND ON NEXT 50M 
    MAXSIZE 2G
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE
    SEGMENT SPACE MANAGEMENT AUTO;

-- Asignar cuota al usuario del esquema TurismoUQ 
ALTER USER bd_proyecto QUOTA UNLIMITED ON ts_historico_reservas;

-- =====================================================================
-- 2. TABLA DE HISTÓRICO DE RESERVAS ALOJADA EN EL TABLESPACE DEDICADO
-- Almacena las reservas cerradas (COMPLETADAS o CANCELADAS) migradas
-- desde el esquema transaccional para consulta gerencial y auditoría.
-- =====================================================================
CREATE TABLE reserva_historico (
    id_historico       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_reserva         NUMBER         NOT NULL,
    id_cliente         NUMBER         NOT NULL,
    id_alojamiento     NUMBER         NOT NULL,
    fecha_creacion     DATE           NOT NULL,
    fecha_checkin      DATE           NOT NULL,
    fecha_checkout     DATE           NOT NULL,
    estado             VARCHAR2(12)   NOT NULL,
    fecha_cancelacion  DATE,
    valor_total        NUMBER(12,2)   NOT NULL,
    fecha_migracion    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_reserva_historico PRIMARY KEY (id_historico)
)
TABLESPACE ts_historico_reservas;

COMMENT ON TABLE reserva_historico IS 'Repositorio historico de reservas finalizadas o canceladas, aislado en tablespace propio.';


-- Pruebas

-- 1. Verificar la existencia, estado y tamaño del tablespace en el motor
SELECT tablespace_name,
       status,
       extent_management,
       allocation_type,
       segment_space_management
  FROM user_tablespaces
 WHERE tablespace_name = 'TS_HISTORICO_RESERVAS';

-- 2. Confirmar la ruta y configuración del Datafile asociado
SELECT tablespace_name,
       file_name,
       bytes / 1024 / 1024 AS tamano_mb,
       autoextensible,
       maxbytes / 1024 / 1024 AS maximo_mb
  FROM dba_data_files
 WHERE tablespace_name = 'TS_HISTORICO_RESERVAS';

-- 3. Confirmar que la tabla 'RESERVA_HISTORICO' reside en el nuevo tablespace
SELECT table_name,
       tablespace_name,
       status,
       logging
  FROM user_tables
 WHERE table_name = 'RESERVA_HISTORICO';

